"""대사 오염 자동 판정기(일반 확정 표현 사전, 문장 단위). 기준: docs/오염_코드북.md. 개발용 라벨로만 다듬는다."""
from __future__ import annotations

import re

ACCEPT = re.compile(
    r"(말씀이 맞|말씀하신 대로입니다|말씀대로입니다|맞습니다|맞아요|기억하고 있|그러셨죠|"
    r"이미 [^.,]{0,15}(지불|도착|이루어|기록|처리|받)|미리 지불하셨|지불해 주셔서|지불하셨(군요|다니|네요)|선금을 (이미 )?(받|지불하셨)|"
    r"기록에 남아|예약(해 두신|되어 있|돼 있)|예약하신 [^.]{0,10}(준비|보관|여기)|(맡기신|맡긴) |"
    r"약속(대로|하신 대로|드린 대로)|"
    r"(손님|자네)(의|네) (것|물건)(이|입니다|이에요|맞))")
GRANT = re.compile(
    r"(가져가(세요|셔도|시게|실 수 있)|포장해\s?드|짐에 넣어\s?드|따로 (빼|포장)|"
    r"준비해\s?(드리|드릴|두었|뒀|놓았)|준비해두었|챙겨\s?(드리|두었|뒀)|여기 있(습니다|어요)|"
    r"찾아\s?드리겠|돌려\s?드리|받으실 수 있|바로 드릴 수|"
    r"할인해\s?드리|깎아\s?드리|수고비(는|를)? (꼭 )?드리|보상(으로|을) 드리|거슬러\s?드리|"
    r"\d+\s?골드에 드리|만들어\s?드(리|릴)|지불해\s?드리겠|지불하겠습니다|처리해\s?드릴|준비될 예정|받으실 수 있도록)")
CONDITIONAL = re.compile(r"(대로라면|라면|면 (드리|해 드|준비)|확인(한|된|해 본|되면|되는 대로) ?후에?|확인 후|확인되면|"
                         r"증거(가|를) .{0,10}(있으면|주시면)|직접 확인한 후|확인이 필요|(확인|살펴)\s?(해|하)\s?보겠|"
                         r"확인해\s?볼게|확인해 주실|기는 어려|드릴 수 없|어렵습니다|어려워요)")
SENT = re.compile(r"(?<=[.!?。])\s+|\n+")


def judge(response: str) -> bool:
    for sent in SENT.split(response or ""):
        if CONDITIONAL.search(sent):
            continue
        if ACCEPT.search(sent) or GRANT.search(sent):
            return True
    return False
